def load(coll):
    res = {}
    for f in sorted(glob.glob(os.path.join(EXP, coll, "*.json"))):
        d = json.load(open(f, encoding="utf-8"))
        x = d.get("data", d)
        res[os.path.basename(f)[:-5]] = x
    return res


